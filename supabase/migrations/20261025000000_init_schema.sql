-- 0. 확장 모듈 활성화
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. 단어장 엔트리 테이블 (품사별 1행 정규화 구조)
CREATE TABLE IF NOT EXISTS public.vocab_entries (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),

    -- 분류 메타데이터 (비워져 있을 수 있으므로 NULL 허용)
    book_title TEXT DEFAULT NULL,
    chapter_name TEXT DEFAULT NULL,

    -- 영단어 및 발음/오디오 정보
    word TEXT NOT NULL CHECK (char_length(trim(word)) > 0),
    phonetic TEXT DEFAULT NULL,              -- 예: "/ˈprez.ənt/"
    audio_url TEXT DEFAULT NULL,             -- 사전 MP3 URL 또는 Supabase Storage URL

    -- 품사별 의미 및 예문 (영단어 1개가 여러 의미를 가질 때 품사별로 행을 달리함)
    part_of_speech TEXT NOT NULL DEFAULT '', -- 예: "n.", "v.", "adj.", "adv."
    meaning_ko TEXT NOT NULL,                -- 예: "선물", "제출하다"
    example_sentence TEXT DEFAULT NULL,      -- 아랫줄에 표시할 영어 예문
    example_translation TEXT DEFAULT NULL,   -- 예문 한글 해석 (선택)

    -- 학습 통계 및 오답률(틀린 확률) 자동 계산 컬럼
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    wrong_count INTEGER NOT NULL DEFAULT 0 CHECK (wrong_count >= 0),
    error_rate NUMERIC(5, 2) GENERATED ALWAYS AS (
        CASE WHEN attempt_count > 0
             THEN ROUND((wrong_count::NUMERIC / attempt_count::NUMERIC) * 100, 2)
             ELSE 0.00
        END
    ) STORED,
    is_last_wrong BOOLEAN NOT NULL DEFAULT FALSE,

    -- 입력된 순서 보장용 시퀀스 및 타임스탬프
    seq_order BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. 사용자 환경설정 테이블 (상단바 폰트 크기, 표시 컬럼 설정, 플래시카드 타이머)
CREATE TABLE IF NOT EXISTS public.user_settings (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    font_size_scale NUMERIC(3, 2) NOT NULL DEFAULT 1.00 CHECK (font_size_scale BETWEEN 0.70 AND 1.80),
    show_phonetic BOOLEAN NOT NULL DEFAULT TRUE,
    show_pos BOOLEAN NOT NULL DEFAULT TRUE,
    show_example BOOLEAN NOT NULL DEFAULT TRUE,
    flashcard_auto_advance_sec INTEGER NOT NULL DEFAULT 3 CHECK (flashcard_auto_advance_sec BETWEEN 0 AND 60),
    flashcard_initial_side TEXT NOT NULL DEFAULT 'WORD' CHECK (flashcard_initial_side IN ('WORD', 'MEANING')),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. 고속 필터링 및 5종 정렬을 위한 인덱스 설계
CREATE INDEX IF NOT EXISTS idx_vocab_user_book_chapter
    ON public.vocab_entries (user_id, book_title, chapter_name);

CREATE INDEX IF NOT EXISTS idx_vocab_word_asc
    ON public.vocab_entries (user_id, LOWER(word) ASC, part_of_speech ASC);

CREATE INDEX IF NOT EXISTS idx_vocab_word_desc
    ON public.vocab_entries (user_id, LOWER(word) DESC, part_of_speech ASC);

CREATE INDEX IF NOT EXISTS idx_vocab_seq_order
    ON public.vocab_entries (user_id, seq_order ASC);

CREATE INDEX IF NOT EXISTS idx_vocab_error_rate
    ON public.vocab_entries (user_id, error_rate DESC, wrong_count DESC);

-- 4. updated_at 자동 갱신 트리거
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_vocab_entries_updated_at ON public.vocab_entries;
CREATE TRIGGER trg_vocab_entries_updated_at
    BEFORE UPDATE ON public.vocab_entries
    FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

DROP TRIGGER IF EXISTS trg_user_settings_updated_at ON public.user_settings;
CREATE TRIGGER trg_user_settings_updated_at
    BEFORE UPDATE ON public.user_settings
    FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

-- 5. 오답/정답 기록 원자적 업데이트 RPC 함수
--    클라이언트에서 틀렸음을 표시하거나 정답 처리할 때 동시성 문제 없이 즉시 확률을 갱신합니다.
CREATE OR REPLACE FUNCTION public.record_vocab_attempt(
    p_entry_id UUID,
    p_is_wrong BOOLEAN
)
RETURNS public.vocab_entries
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_updated public.vocab_entries;
BEGIN
    UPDATE public.vocab_entries
    SET
        attempt_count = attempt_count + 1,
        wrong_count = CASE WHEN p_is_wrong THEN wrong_count + 1 ELSE wrong_count END,
        is_last_wrong = p_is_wrong,
        updated_at = NOW()
    WHERE id = p_entry_id
    RETURNING * INTO v_updated;

    RETURN v_updated;
END;
$$;

-- 6. 책제목 및 단원 목록 조회용 뷰 (드롭다운 필터 바인딩용)
CREATE OR REPLACE VIEW public.vocab_book_chapter_summary AS
SELECT
    user_id,
    COALESCE(book_title, '') AS book_title,
    COALESCE(chapter_name, '') AS chapter_name,
    COUNT(*) AS entry_count,
    ROUND(AVG(error_rate), 2) AS avg_error_rate
FROM public.vocab_entries
GROUP BY user_id, COALESCE(book_title, ''), COALESCE(chapter_name, '');

-- 7. Row Level Security (RLS) 정책 설정
ALTER TABLE public.vocab_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_settings ENABLE ROW LEVEL SECURITY;

-- 익명(데모) 또는 로그인 사용자 모두 본인 데이터 접근 허용
CREATE POLICY "Users can manage own vocab_entries"
    ON public.vocab_entries
    FOR ALL
    USING (auth.uid() = user_id OR user_id IS NULL)
    WITH CHECK (auth.uid() = user_id OR user_id IS NULL);

CREATE POLICY "Users can manage own user_settings"
    ON public.user_settings
    FOR ALL
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- 8. Supabase Storage 오디오 버킷('vocab-audio') 생성
INSERT INTO storage.buckets (id, name, public)
VALUES ('vocab-audio', 'vocab-audio', true)
ON CONFLICT (id) DO NOTHING;
